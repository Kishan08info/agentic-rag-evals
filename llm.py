"""Provider-agnostic LLM client with an honest extractive fallback.

If LLM_BASE_URL + LLM_API_KEY are set (any OpenAI-compatible chat-completions
endpoint), answers are generated by the LLM with a strict "answer only from the
context, cite sources" instruction. Otherwise the agent answers extractively:
it returns the most relevant retrieved passage(s), labeled as such. The fallback
needs no API key and is what the evals run against.
"""
import json
import os
import urllib.request
from typing import List, Dict

LLM_BASE_URL = os.getenv("LLM_BASE_URL", "").rstrip("/")
LLM_API_KEY = os.getenv("LLM_API_KEY", "")
LLM_MODEL = os.getenv("LLM_MODEL", "gpt-4o-mini")
LLM_TIMEOUT_S = int(os.getenv("LLM_TIMEOUT_S", "30"))


def llm_available() -> bool:
    return bool(LLM_BASE_URL and LLM_API_KEY)


def chat(messages: List[Dict[str, str]]) -> str:
    """Call an OpenAI-compatible /chat/completions endpoint. Raises on failure."""
    url = f"{LLM_BASE_URL}/chat/completions"
    payload = json.dumps({"model": LLM_MODEL, "messages": messages,
                          "temperature": 0.2}).encode()
    req = urllib.request.Request(
        url, data=payload,
        headers={"Content-Type": "application/json",
                 "Authorization": f"Bearer {LLM_API_KEY}"})
    with urllib.request.urlopen(req, timeout=LLM_TIMEOUT_S) as resp:
        body = json.load(resp)
    return body["choices"][0]["message"]["content"].strip()


GENERATE_SYSTEM = (
    "You answer questions using ONLY the provided context passages. "
    "Every factual claim must cite the passage it came from as [source: filename]. "
    "If the context does not contain the answer, reply exactly: "
    "\"I don't know based on the available documents.\""
)


def generative_answer(question: str, retrieved: List[Dict]) -> str:
    context = "\n\n".join(
        f"[source: {r['source']}]\n{r['text']}" for r in retrieved)
    return chat([
        {"role": "system", "content": GENERATE_SYSTEM},
        {"role": "user",
         "content": f"Context:\n{context}\n\nQuestion: {question}"},
    ])


def extractive_answer(question: str, retrieved: List[Dict], n: int = 2) -> str:
    """No-key fallback: return the top passages verbatim, clearly labeled."""
    parts = [f"[source: {r['source']}] {r['text']}" for r in retrieved[:n]]
    return ("(Extractive answer — no LLM key configured; showing the most "
            "relevant passages verbatim.)\n\n" + "\n\n".join(parts))


def generate_answer(question: str, retrieved: List[Dict]) -> tuple[str, str]:
    """Returns (answer, mode) where mode is 'generative' or 'extractive'."""
    if llm_available():
        try:
            return generative_answer(question, retrieved), "generative"
        except Exception as e:  # never fail the request; degrade honestly
            print(f"LLM call failed ({e}); falling back to extractive answer.")
    return extractive_answer(question, retrieved), "extractive"
